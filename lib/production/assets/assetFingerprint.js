// lib/production/assets/assetFingerprint.js
// Pure — no I/O, no fs, no network. Safe on server and client.
//
// ── Two identities, deliberately separate ────────────────────────────────
//
//   contentHash          sha256 of the file BYTES. Answers "are these the
//                        same file?" Computed by assetStore at save time.
//
//   semanticFingerprint  sha256 of the normalized REQUEST INTENT. Answers
//                        "would generating this again serve the same
//                        purpose?" Computed here.
//
// Content hashing alone can never produce a cache hit, because generative
// providers are non-deterministic — the same prompt yields different bytes
// every time. The semantic fingerprint is therefore the only thing that can
// actually save money.
//
// ── What is deliberately EXCLUDED ────────────────────────────────────────
// providerId, model, provider job id, timestamps, cost, approval ids,
// storage path, runtime status.
//
// This is the load-bearing decision: an asset generated by one provider must
// satisfy an identical request later routed to a different provider. If model
// or provider entered the fingerprint, switching providers would silently
// invalidate the whole library and re-spend on work already paid for.
//
// v1 is strict and deterministic. No embeddings, no similarity scoring, no
// fuzzy matching — a near-miss is a MISS.

export const FINGERPRINT_SCHEMA_VERSION = 1;

// Bumped when normalization or the included field set changes, so old
// fingerprints cannot collide with new ones under different rules.
export const PLANNER_VERSION = 1;

/**
 * Deterministic text normalization.
 *
 * Case is folded because "A CLUTTERED DESK" and "a cluttered desk" request the
 * same picture — a generator treats them identically, so treating them as
 * distinct would just buy the same image twice. Punctuation is deliberately
 * PRESERVED: it carries real meaning in prompts (negations, lists, weights).
 */
export function normalizePromptText(value) {
  if (typeof value !== 'string') return '';
  return value
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f-\u009f]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/**
 * Brand identity normalization. Brands arrive as free text ("Digital Diamond
 * AI"), so casing and spacing must not fragment the cache — while remaining
 * strict enough that two genuinely different brands never collide.
 */
export function normalizeBrandId(value) {
  if (typeof value !== 'string') return '';
  return value.replace(/\s+/g, ' ').trim().toLowerCase();
}

function normalizeAspectRatio(value) {
  if (typeof value !== 'string') return null;
  const t = value.trim().replace(/\s+/g, '');
  return /^\d{1,2}:\d{1,2}$/.test(t) ? t : null;
}

function num(v) {
  return Number.isFinite(v) ? v : null;
}

/**
 * The canonical, ordered subject of the fingerprint. Exposed so validators can
 * assert exactly what is and is not included, rather than inferring it from a
 * hash.
 */
export function fingerprintSubject(request) {
  return {
    v: FINGERPRINT_SCHEMA_VERSION,
    plannerVersion: PLANNER_VERSION,
    capability: typeof request?.capability === 'string' ? request.capability : null,
    brandId: normalizeBrandId(request?.brandId),
    prompt: normalizePromptText(request?.prompt),
    negativePrompt: normalizePromptText(request?.negativePrompt),
    aspectRatio: normalizeAspectRatio(request?.aspectRatio),
    width: num(request?.width),
    height: num(request?.height),
    durationSeconds: num(request?.durationSeconds),
    outputCount: num(request?.outputCount) ?? 1,
    consistencyGroupId: typeof request?.consistencyGroupId === 'string' && request.consistencyGroupId.trim()
      ? request.consistencyGroupId.trim()
      : null,
  };
}

/**
 * Stable serialization: keys are emitted in a fixed order, so object key
 * ordering in the caller can never change the fingerprint.
 */
export function serializeSubject(subject) {
  const ORDER = [
    'v', 'plannerVersion', 'capability', 'brandId', 'prompt', 'negativePrompt',
    'aspectRatio', 'width', 'height', 'durationSeconds', 'outputCount', 'consistencyGroupId',
  ];
  return JSON.stringify(ORDER.map(k => [k, subject[k] ?? null]));
}

/**
 * @param {object} request an AssetRequest
 * @param {(text: string) => string} hasher sha256 hex hasher (injected to keep this module pure)
 * @returns {string} 64-char hex fingerprint
 */
export function computeSemanticFingerprint(request, hasher) {
  return hasher(serializeSubject(fingerprintSubject(request)));
}

/** Fields a fingerprint must NEVER depend on — asserted by the validator. */
export const FINGERPRINT_EXCLUDED_FIELDS = Object.freeze([
  'providerId', 'model', 'providerJobId', 'productionJobId', 'generatedAt',
  'timestamp', 'cost', 'approvalRef', 'storagePath', 'status', 'assetId', 'contentHash',
]);
